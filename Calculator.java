class Calculator{
	
	public static int add(int number, int otherNumber){
		int total = number + otherNumber;
		
		//System.out.println("The Addition of "+ number +" and " + otherNumber + " is " +total);
		return total;
	}
	
	
	public static int subtract(int number, int otherNumber){
		int total = number - otherNumber;
		
		
		//System.out.println("The Subtraction of "+ number +" and " + otherNumber+ " is " +total);
		return total;
	}
	
	public static int multiplication(int number, int otherNumber){
		int total = number * otherNumber;
		
		
		//System.out.println("The Subtraction of "+ number +" and " + otherNumber+ " is " +total);
		return total;
	}
	
	public static int division(int number, int otherNumber){
		int total = number / otherNumber;
		
		
		//System.out.println("The Subtraction of "+ number +" and " + otherNumber+ " is " +total);
		return total;
	}
	public static int modulus(int number, int otherNumber){
		int total = number % otherNumber;
		
		
		//System.out.println("The Subtraction of "+ number +" and " + otherNumber+ " is " +total);
		return total;
	}
	
}